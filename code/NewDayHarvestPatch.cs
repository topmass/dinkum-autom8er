using BepInEx;
using BepInEx.Configuration;
using BepInEx.Logging;
using HarmonyLib;
using Mirror;
using System.Collections;
using System.Collections.Generic;
using System.Reflection;
using UnityEngine;

namespace Autom8er
{

    // Patch to trigger harvest processing after day change completes
    // This is much more efficient than continuous scanning since growth machines
    // (bee houses, key cutters, worm farms, crab pots) only update on day change
    [HarmonyPatch(typeof(WorldManager), "refreshAllChunksNewDay")]
    public static class NewDayHarvestPatch
    {
        private const float DAY_CHANGE_PHASE_DELAY_SECONDS = 0.5f;
        private const float POST_QUARRY_PHASE_DELAY_SECONDS = 0.5f;
        private static bool phasedHarvestRunning = false;

        // Save/load safety net: if the phased coroutine died without its finally running,
        // a stale true here would silence day-change harvesting until app restart.
        public static void ResetRunningFlag()
        {
            phasedHarvestRunning = false;
        }

        // MoveNext is the actual coroutine method generated by the compiler
        static void Postfix()
        {
            if (NetworkMapSharer.Instance.isServer)
            {
                TryStartPhasedHarvest(WorldManager.Instance, 2f, "Autom8er: Processing day-change harvests...", "Autom8er: Day-change harvest kickoff complete");
            }
        }

        public static bool TryStartPhasedHarvest(MonoBehaviour runner, float initialDelay, string startLog, string endLog)
        {
            if (runner == null || phasedHarvestRunning)
                return false;

            phasedHarvestRunning = true;
            runner.StartCoroutine(RunPhasedHarvestProcessing(initialDelay, startLog, endLog));
            return true;
        }

        public static System.Collections.IEnumerator RunPhasedHarvestProcessing(float initialDelay, string startLog, string endLog)
        {
            try
            {
                if (initialDelay > 0f)
                    yield return new UnityEngine.WaitForSeconds(initialDelay);

                // The end-of-day save usually starts during the initial delay. Each phase
                // moves items between the map and chests, so it starts only between saves.
                while (Plugin.IsSaving)
                    yield return null;

                if (NetworkMapSharer.Instance == null || !NetworkMapSharer.Instance.isServer || WorldManager.Instance == null)
                    yield break;

                ConveyorHelper.ActivateAllOutdoorAutomationChests();
                Plugin.Log.LogInfo(startLog);
                WorldManager.Instance.StartCoroutine(HarvestHelper.ProcessHarvestableMachines());
                yield return new WaitForSeconds(DAY_CHANGE_PHASE_DELAY_SECONDS);
                while (Plugin.IsSaving)
                    yield return null;
                WorldManager.Instance.StartCoroutine(VacuumCrateHelper.ProcessDayChangeVacuumHarvests());
                yield return new WaitForSeconds(DAY_CHANGE_PHASE_DELAY_SECONDS);
                while (Plugin.IsSaving)
                    yield return null;
                FishPondHelper.ProcessPondAndTerrariumOutput();
                yield return new WaitForSeconds(POST_QUARRY_PHASE_DELAY_SECONDS);
                while (Plugin.IsSaving)
                    yield return null;
                QuarryHelper.ProcessDayChangeQuarries();
                Plugin.Log.LogInfo(endLog);
            }
            finally
            {
                phasedHarvestRunning = false;
            }
        }
    }
}
